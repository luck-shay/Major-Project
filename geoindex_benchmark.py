def kdtree_range_query(tree, query_box):
    x0, y0, x1, y1 = query_box
    cx, cy = (x0+x1)/2, (y0+y1)/2
    r = max(x1-x0, y1-y0) / 2 * 1.415  # circumscribed circle radius
    candidates = tree.query_ball_point([cx, cy], r, p=np.inf)  # Chebyshev = box
    return candidates

def kdtree_knn_query(tree, qx, qy, k):
    dists, idxs = tree.query([qx, qy], k=k)
    return idxs

