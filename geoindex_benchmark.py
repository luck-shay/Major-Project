# 1. R-tree (STR bulk-load) via libspatialindex
# ══════════════════════════════════════════════════════════════════════════════
def build_rtree_str(points):
    """Build R-tree using STR bulk loading (via rtree library)"""
    p = rtree_index.Property()
    p.leaf_capacity = 50
    p.fill_factor = 0.9
    p.index_capacity = 50
    p.dimension = 2

    def gen():
        for i, (x, y) in enumerate(points):
            yield (i, (x, y, x, y), None)

    t0 = time.perf_counter()
    idx = rtree_index.Index(gen(), properties=p)
    build_time = time.perf_counter() - t0
    return idx, build_time

def rtree_range_query(idx, points, query_box):
    """Range query on rtree; returns result list"""
    x0, y0, x1, y1 = query_box
    return list(idx.intersection((x0, y0, x1, y1)))

def rtree_knn_query(idx, points, qx, qy, k):
    """kNN query on rtree"""
    return list(idx.nearest((qx, qy, qx, qy), k))

