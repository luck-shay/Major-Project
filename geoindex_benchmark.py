# 3. Geohash B-tree (sorted list of geohash strings → binary search)
# ══════════════════════════════════════════════════════════════════════════════
GEOHASH_PRECISION = 7  # ~150m precision

def encode_geohash_fast(lat, lon, precision=GEOHASH_PRECISION):
    """Fast geohash encoding (maps [0,1]^2 to lat/lon space first)"""
    # Map [0,1] → lat [-90, 90] and lon [-180, 180]
    real_lat = lat * 180 - 90
    real_lon = lon * 360 - 180
    try:
        return pgh.encode(real_lat, real_lon, precision=precision)
    except:
        return 'zzzzzzz'

def build_geohash(points, precision=GEOHASH_PRECISION):
    t0 = time.perf_counter()
    hashes = [(encode_geohash_fast(y, x, precision), i) for i, (x, y) in enumerate(points)]
    hashes.sort(key=lambda h: h[0])
    build_time = time.perf_counter() - t0
    keys = [h[0] for h in hashes]
    vals = [h[1] for h in hashes]
    return (keys, vals), build_time

def geohash_range_query(gh_index, query_box, precision=GEOHASH_PRECISION):
    keys, vals = gh_index
    x0, y0, x1, y1 = query_box
    # Encode all 9 cells covering the query box
    cx, cy = (x0+x1)/2, (y0+y1)/2
    prefix = encode_geohash_fast(cy, cx, precision)[:max(1, precision-2)]
    lo = bisect.bisect_left(keys, prefix)
    hi = bisect.bisect_right(keys, prefix + '~')
    # Return indices in range (with false positives — post-filter in real use)
    return vals[lo:hi]

