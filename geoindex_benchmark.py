# Hilbert R-tree insert (same underlying structure)
idx_hrt, _ = build_hilbert_rtree(pts)
t0 = time.perf_counter()
for i, pt in enumerate(NEW_PTS):
    idx_hrt.insert(len(pts)+i, (pt[0], pt[1], pt[0], pt[1]))
hrt_tps = len(NEW_PTS) / (time.perf_counter() - t0)
RESULTS['insert_tps']['hilbert_rtree'] = round(hrt_tps, 1)
print(f'   Hilbert R-tree: {hrt_tps:,.0f} TPS')

# KD-tree: rebuild-on-insert simulation (batch of 100)
BATCH = 100
t0 = time.perf_counter()
current = pts.copy()
for i in range(0, len(NEW_PTS), BATCH):
    batch = NEW_PTS[i:i+BATCH]
    current = np.vstack([current, batch])
    _ = cKDTree(current[-min(len(current), 50000):], leafsize=16)  # rolling rebuild
kd_tps = len(NEW_PTS) / (time.perf_counter() - t0)
RESULTS['insert_tps']['kdtree'] = round(kd_tps, 1)
print(f'   KD-tree (batch rebuild): {kd_tps:,.0f} TPS')

# Geohash insert (sorted list insert = O(log n) via bisect)
gh_idx, _ = build_geohash(pts)
keys, vals = gh_idx
t0 = time.perf_counter()
for i, pt in enumerate(NEW_PTS):
    h = encode_geohash_fast(pt[1], pt[0])
    pos = bisect.bisect_left(keys, h)
    keys.insert(pos, h)
    vals.insert(pos, len(pts)+i)
gh_tps = len(NEW_PTS) / (time.perf_counter() - t0)
RESULTS['insert_tps']['geohash'] = round(gh_tps, 1)
print(f'   Geohash B-tree: {gh_tps:,.0f} TPS')

