def measure_ms(fn, n_warmup=3, n_repeat=None):
    """Measure median execution time of fn() in milliseconds"""
    # Warmup
    for _ in range(n_warmup):
        fn()
    # Measure
    times = []
    reps = n_repeat or N_QUERIES
    for _ in range(reps):
        t0 = time.perf_counter()
        fn()
        times.append((time.perf_counter() - t0) * 1000)
    return float(np.median(times)), float(np.std(times)), float(np.percentile(times, 95))

def benchmark_index(name, points, build_fn, range_fn, knn_fn, insert_fn=None):
    """Full benchmark of one index on one dataset. Returns dict of metrics."""
    print(f'   [{name}] Building index on {len(points):,} points...', end='')

    # ── BUILD ────────────────────────────────────────────────────────────────
    mem_before = get_memory_mb()
    idx, build_time = build_fn(points)
    mem_after = get_memory_mb()
    index_size_mb = max(0, mem_after - mem_before)
    print(f' {build_time:.2f}s, ~{index_size_mb:.0f}MB')

    result = {
        'build_time_s': round(build_time, 3),
        'index_size_mb': round(index_size_mb, 1),
        'range_query_ms': {},
        'knn_query_ms': {},
        'insert_tps': None,
    }

    # ── RANGE QUERIES ────────────────────────────────────────────────────────
    print(f'   [{name}] Range queries...', end='')
    for sel, label in zip(SELECTIVITIES, SEL_LABELS):
        queries = RANGE_QUERIES[sel]
        i = 0
        def rq():
            nonlocal i
            range_fn(idx, queries[i % len(queries)])
            i += 1
        med, std, p95 = measure_ms(rq)
        result['range_query_ms'][label] = {'median': round(med, 4), 'std': round(std, 4), 'p95': round(p95, 4)}
        print(f' {label}:{med:.2f}ms', end='')
    print()

    # ── kNN QUERIES ──────────────────────────────────────────────────────────
    print(f'   [{name}] kNN queries...', end='')
    for k in K_VALUES:
        qi = 0
        def kq():
            nonlocal qi
            qx, qy = KNN_QUERIES[qi % len(KNN_QUERIES)]
            knn_fn(idx, qx, qy, k)
            qi += 1
        med, std, p95 = measure_ms(kq)
        result['knn_query_ms'][str(k)] = {'median': round(med, 4), 'std': round(std, 4), 'p95': round(p95, 4)}
        print(f' k={k}:{med:.2f}ms', end='')
    print()

    # ── INSERT THROUGHPUT ────────────────────────────────────────────────────
    if insert_fn is not None:
        print(f'   [{name}] Insert throughput...', end='')
        new_pts = np.random.uniform(0, 1, size=(1000, 2))
        t0 = time.perf_counter()
        for i, pt in enumerate(new_pts):
            insert_fn(idx, pt, len(points) + i)
        elapsed = time.perf_counter() - t0
        tps = len(new_pts) / elapsed
        result['insert_tps'] = round(tps, 1)
        print(f' {tps:.0f} TPS')

    gc.collect()
    return result

