# 6. Hilbert B-tree (sorted array + binary search)
# ══════════════════════════════════════════════════════════════════════════════
def build_hilbert_btree(points):
    t0 = time.perf_counter()
    hvals = np.array([xy_to_hilbert(x, y, order=14) for x, y in points], dtype=np.int64)
    order = np.argsort(hvals)
    sorted_hvals = hvals[order]
    sorted_pts = points[order]
    build_time = time.perf_counter() - t0
    return (sorted_hvals, sorted_pts, order), build_time

def hilbert_btree_range_query(hbtree, query_box):
    sorted_hvals, sorted_pts, order = hbtree
    x0, y0, x1, y1 = query_box
    # Get hilbert range for box corners
    h_corners = [xy_to_hilbert(x, y, order=14) for x,y in [(x0,y0),(x0,y1),(x1,y0),(x1,y1)]]
    h_lo = min(h_corners)
    h_hi = max(h_corners)
    lo = bisect.bisect_left(sorted_hvals, h_lo)
    hi = bisect.bisect_right(sorted_hvals, h_hi)
    # Post-filter
    candidates = sorted_pts[lo:hi]
    mask = (candidates[:,0] >= x0) & (candidates[:,0] <= x1) & \
           (candidates[:,1] >= y0) & (candidates[:,1] <= y1)
    return candidates[mask]

