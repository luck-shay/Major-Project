# 4. Hilbert curve R-tree (sort by Hilbert value, then use R-tree on sorted data)
# ══════════════════════════════════════════════════════════════════════════════
def xy_to_hilbert(x, y, order=16):
    """Convert (x,y) in [0,1]^2 to Hilbert curve index (integer)"""
    n = 1 << order
    xi = int(x * (n - 1))
    yi = int(y * (n - 1))
    xi = max(0, min(n-1, xi))
    yi = max(0, min(n-1, yi))
    rx, ry, s, d = 0, 0, 0, 0
    s = n >> 1
    while s > 0:
        rx = 1 if (xi & s) > 0 else 0
        ry = 1 if (yi & s) > 0 else 0
        d += s * s * ((3 * rx) ^ ry)
        # Rotate
        if ry == 0:
            if rx == 1:
                xi = s - 1 - xi
                yi = s - 1 - yi
            xi, yi = yi, xi
        s >>= 1
    return d

def build_hilbert_rtree(points):
    """Build R-tree with Hilbert-ordered bulk loading"""
    t0 = time.perf_counter()
    # Compute Hilbert values for sorting
    hvals = np.array([xy_to_hilbert(x, y, order=12) for x, y in points])
    order = np.argsort(hvals)
    sorted_pts = points[order]
    # Build R-tree on Hilbert-ordered data
    p = rtree_index.Property()
    p.leaf_capacity = 50
    p.fill_factor = 1.0  # 100% fill for sorted data = packed
    p.dimension = 2

    def gen():
        for i, (x, y) in enumerate(sorted_pts):
            orig_i = int(order[i])
            yield (orig_i, (x, y, x, y), None)

    idx = rtree_index.Index(gen(), properties=p)
    build_time = time.perf_counter() - t0
    return idx, build_time

