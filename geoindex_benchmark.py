# 5. PR-Quadtree (pure Python, cache-friendly implementation)
# ══════════════════════════════════════════════════════════════════════════════
class QuadNode:
    __slots__ = ['cx','cy','hw','points','children']
    def __init__(self, cx, cy, hw):
        self.cx = cx; self.cy = cy; self.hw = hw
        self.points = []   # list of (x, y, idx)
        self.children = None

QUAD_CAPACITY = 16

def quad_insert(node, x, y, idx, depth=0):
    if node.children is None:
        node.points.append((x, y, idx))
        if len(node.points) > QUAD_CAPACITY and depth < 20:
            quad_subdivide(node, depth)
    else:
        quad_insert_child(node, x, y, idx, depth)

def quad_insert_child(node, x, y, idx, depth):
    q = (1 if x >= node.cx else 0) + (2 if y >= node.cy else 0)
    quad_insert(node.children[q], x, y, idx, depth+1)

def quad_subdivide(node, depth):
    hw = node.hw / 2
    node.children = [
        QuadNode(node.cx - hw, node.cy - hw, hw),
        QuadNode(node.cx + hw, node.cy - hw, hw),
        QuadNode(node.cx - hw, node.cy + hw, hw),
        QuadNode(node.cx + hw, node.cy + hw, hw),
    ]
    for (px, py, pi) in node.points:
        quad_insert_child(node, px, py, pi, depth+1)
    node.points = []

def quad_range_query(node, x0, y0, x1, y1, results):
    if node.cx + node.hw < x0 or node.cx - node.hw > x1:
        return
    if node.cy + node.hw < y0 or node.cy - node.hw > y1:
        return
    if node.children is None:
        for (px, py, pi) in node.points:
            if x0 <= px <= x1 and y0 <= py <= y1:
                results.append(pi)
    else:
        for child in node.children:
            quad_range_query(child, x0, y0, x1, y1, results)

def build_quadtree(points):
    t0 = time.perf_counter()
    root = QuadNode(0.5, 0.5, 0.5)
    for i, (x, y) in enumerate(points):
        quad_insert(root, x, y, i)
    build_time = time.perf_counter() - t0
    return root, build_time

